package com.zstore.model;

public class Tag {
    private long idTag;
    private String namaTag;
    private int productCount;

    public long getIdTag() { return idTag; }
    public void setIdTag(long idTag) { this.idTag = idTag; }

    public String getNamaTag() { return namaTag; }
    public void setNamaTag(String namaTag) { this.namaTag = namaTag; }

    public int getProductCount() { return productCount; }
    public void setProductCount(int productCount) { this.productCount = productCount; }
}

